public class Variables {
    public static void main(String[] args) {
        int x = 4;
        System.out.println(x);
        System.out.println(x + 7);
        x = 8;
        System.out.println(x);
        System.out.println("Modified value of y: ");
        int y = 5;
        System.out.println(y);
        System.out.println(y * 3);
        System.out.println(y);
        y = y * 3;
        System.out.println(y);
    }
}